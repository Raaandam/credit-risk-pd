_TOKEN = re.compile(r"\{\{(\w+)\}\}")


def placeholders() -> list[str]:
    return sorted(set(_TOKEN.findall(TEMPLATE)))


def render(context: dict) -> str:
    missing = [k for k in placeholders() if k not in context]
    if missing:
        raise KeyError(f"Report context missing: {missing}")
    return _TOKEN.sub(lambda m: str(context[m.group(1)]), TEMPLATE)


def render_placeholder() -> str:
    ctx = {k: f"<<RUNTIME: {k}>>" for k in placeholders()}
    ctx["report_status"] = ("TEMPLATE - not yet run. Run `python -m credit_risk_pd.pipeline "
                            "--data data/raw/accepted_2007_to_2018Q4.csv` to fill in results.")
    return render(ctx)


# --------------------------------------------------------------------------- formatting
def _fmt(v, floatfmt: str) -> str:
    if isinstance(v, (float, np.floating)):
        if np.isnan(v):
            return ""
        if abs(v) >= 1e3 or (float(v).is_integer() and abs(v) >= 1):
            return f"{v:,.0f}"
        return format(v, floatfmt)
    if isinstance(v, (int, np.integer)) and not isinstance(v, bool):
        return f"{v:,}"
    return str(v)


def md_table(df: pd.DataFrame, floatfmt: str = ".4f", max_rows: int | None = None) -> str:
    """DataFrame -> GitHub Markdown table (no tabulate dependency)."""
    if max_rows is not None:
        df = df.head(max_rows)
    cols = [str(c) for c in df.columns]
    lines = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for row in df.itertuples(index=False):
        lines.append("| " + " | ".join(_fmt(v, floatfmt).replace("|", "/") for v in row) + " |")
    return "\n".join(lines)


def save_figures(fig_dir: Path, y_oot, p_sc, p_xgb, score_train, score_oot, losses,
                 var_value: float, el: float) -> list[str]:
    """ROC, calibration, score distribution and loss distribution plots."""
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
        from sklearn.metrics import roc_curve
    except ImportError:
        return []
    fig_dir.mkdir(parents=True, exist_ok=True)
    out = []

    fig, ax = plt.subplots(figsize=(5, 5))
    for name, p in (("Scorecard", p_sc), ("XGBoost", p_xgb)):
        fpr, tpr, _ = roc_curve(y_oot, p)
        ax.plot(fpr, tpr, label=name)
    ax.plot([0, 1], [0, 1], "k--", lw=0.8)
    ax.set(xlabel="False positive rate", ylabel="True positive rate", title="ROC - OOT")
    ax.legend()
    fig.tight_layout(); fig.savefig(fig_dir / "roc_oot.png", dpi=120); plt.close(fig)
    out.append("roc_oot.png")

    fig, ax = plt.subplots(figsize=(5, 5))
    for name, p in (("Scorecard", p_sc), ("XGBoost", p_xgb)):
        d = pd.DataFrame({"y": y_oot, "p": p})
        d["bin"] = pd.qcut(d["p"].rank(method="first"), 10, labels=False)
        g = d.groupby("bin").mean()
        ax.plot(g["p"], g["y"], marker="o", label=name)
    lim = max(np.max(p_sc), np.max(p_xgb))
    ax.plot([0, lim], [0, lim], "k--", lw=0.8)
    ax.set(xlabel="Mean predicted PD", ylabel="Observed default rate", title="Calibration - OOT")
    ax.legend()
    fig.tight_layout(); fig.savefig(fig_dir / "calibration_oot.png", dpi=120); plt.close(fig)
    out.append("calibration_oot.png")

    fig, ax = plt.subplots(figsize=(6, 4))
    ax.hist(score_train, bins=50, alpha=0.5, density=True, label="Train")
    ax.hist(score_oot, bins=50, alpha=0.5, density=True, label="OOT")
    ax.set(xlabel="Scorecard points", title="Score distribution (PSI)")
    ax.legend()
    fig.tight_layout(); fig.savefig(fig_dir / "score_distribution.png", dpi=120); plt.close(fig)
    out.append("score_distribution.png")

    fig, ax = plt.subplots(figsize=(6, 4))
    ax.hist(losses, bins=200, color="#777")
    ax.axvline(el, color="tab:blue", label="EL")
    ax.axvline(var_value, color="tab:red", label="99.9% VaR")
    ax.set(xlabel="Portfolio loss", title="Simulated 1-year loss distribution")
    ax.legend()
    fig.tight_layout(); fig.savefig(fig_dir / "loss_distribution.png", dpi=120); plt.close(fig)
    out.append("loss_distribution.png")
    return out


def write_report(context: dict, path: Path) -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render(context), encoding="utf-8")
    return path


def main() -> None:
    ap = argparse.ArgumentParser(description="Write the unrendered report template.")
    ap.add_argument("--placeholder", action="store_true", help="write template with placeholders")
    ap.add_argument("--out", default="reports/model_validation_report.md")
    args = ap.parse_args()
    if args.placeholder:
        Path(args.out).parent.mkdir(parents=True, exist_ok=True)
        Path(args.out).write_text(render_placeholder(), encoding="utf-8")
        print(f"Template written to {args.out}")


if __name__ == "__main__":
    main()
